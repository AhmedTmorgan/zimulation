"""
المناخ — اشتقاقًا لا فرضًا.

كان المناخ في هذا العالم دالّتَي جيبٍ كتبتُهما بيدي. فإذا سُئل «لماذا
قحطت هذه السنة؟» لم يكن الجواب إلا «لأن دورتي الطويلة بلغت حضيضها»،
وذلك ليس سببًا، هو اسمٌ آخر للأمر الواقع. وأسوأ من ذلك: كان طلوع النجم
مبكّرًا دالّةً في **الجيب نفسه** — فالارتباط الذي يكتشفونه لم يكن في
عالمهم، كان يدي في موضعين.

فصار المناخ هنا أربعةَ أشياء، لكلٍّ منها مرجع:

  **١. الفلك.** ميلُ المحور وترنّحه يغيّران ما يصل الأرضَ من شمسٍ في
  صيف المدار (Milanković؛ وترنّح الاعتدالين دورته نحو ٢٣ ألف سنة).
  وهذا هو ما أنهى الفترةَ الرطبة الإفريقية حقيقةً — لم تجفّ الصحراء
  بمزاجٍ بل لأن الشمس انزاحت (deMenocal et al. 2000).
  **وهذا وحده هو المفروض**: أنا وضعتُ الكوكب في مداره وفي طور بعينه
  من ترنّحه. وما بعده يتبع.

  **٢. المحيط.** مرجّحٌ يُشحن ويُفرَّغ بتأخير: حرارةٌ تتراكم فتُطلَق
  فتُبرَّد فتتراكم (Jin 1997، مرجّح الشحن والتفريغ؛ وقبله Suarez &
  Schopf 1988، المرجّح المؤجَّل). ومن التأخير وحده — بلا دالّة دوريّة
  واحدة — يخرج تذبذبٌ شبهُ دوريّ **غيرُ منتظم**، دورته هنا نحو ستّين
  سنة. وهذا ما يُرصد في المحيط الأطلسي، وهو ما يقود جفافَ الساحل.

  **٣. البراكين.** ثورانٌ يقع كحوادث بواسون، وقدرُه من توزيع ذيلٍ
  ثقيل، ورمادُه يحجب الشمس ثم ينحلّ أُسّيًّا في نحو سنةٍ ونصف.
  فالسنة الباردة المفاجئة لها فاعلٌ لا احتمالٌ أعمى.

  **٤. هم أنفسهم.** أرضٌ تُعرّى بالرعي والحرث ترفع البياض فيقلّ المطر
  فتزداد عريًا (Charney 1975). فجزءٌ من قحطهم صنعُ أيديهم — ولا أحد
  فيهم يعلم ذلك، ولا سبيل له أن يعلمه إلا بقياسٍ طويل.

──────────────────────────────────────────────────────────────────────
**وأمّا النجم.**

كان طلوعُه المبكّر مرتبطًا بالخصب لأني كتبتُ ذلك. وصار مرتبطًا به
لسببٍ يمكن أن يُروى:

  النجم يُرى أوّلَ ما يُرى حين ينحسر عنه ضوءُ الفجر. ورؤيتُه تتوقّف
  على صفاء الهواء. والهواء يكدُره الغبار. والغبار يثيره الجفافُ
  والأرضُ العارية. فالسنة الرطبة هواؤها صافٍ فيُرى النجم **مبكّرًا**،
  والسنة القاحلة هواؤها كدِرٌ فيتأخّر.

فالنجم لا يجلب الخصب — النجمُ والخصبُ عرَضان لشيءٍ ثالث. ومن قال منهم
«طلع النجم فجاء الخير» فقد أصاب في التنبّؤ وأخطأ في العلّة، وهذا أكثر
ما يقع للناس. ونحن لا نصحّح لهم ولا نلمّح.
"""

import math

# ثوابت فلكيّة — ليست من عندي
PRECESSION = 23000.0      # ترنّح الاعتدالين، سنة
OBLIQUITY = 41000.0       # دورة ميل المحور، سنة
ECCENTRIC = 0.0167        # شذوذ المدار (ثابتٌ على مدى عشرة آلاف سنة)

# ------------------------------------------------------------------ مضبوطات
#
# ثوابتُ المرجّح والغبار والرماد. **بنيتُها من مرجع وأرقامُها من يدي** —
# ضُبطت لتعطي دورةً في نحو ستّين سنة (وهي المرصودة في الأطلسي) وسعةً
# تُشبه تقلّب الغلّة. وهي معاملات حرّة تُحصى في البيان مع سائرها، فلا
# يُقال «المناخ صار مشتقًّا» ثم تُخبّأ عشرة أرقام في ملفّ.
K_HEAT = 0.130            # استجابة الرطوبة لما اختُزن قبل التأخير
K_DRAG = 0.055            # تخميدٌ خطّي
K_CUBE = 0.30             # تخميدٌ تكعيبي — يحدّ السعة بلا سقفٍ مفروض
K_PULL = 0.084            # سحبُ الرطوبة من المخزون
K_LEAK = 0.022            # تسرّبُ المخزون
K_SUN_T = 0.032           # ما يبلغ الرطوبةَ من فضل الشمس
K_SUN_H = 0.018           # وما يبلغ المخزون
K_NOISE_T = 0.075         # تشويشٌ سنوي يستثير المرجّح المخمَّد
K_NOISE_H = 0.030
LAG = 6                   # التأخير بالسنين — منه وحده يجيء التذبذب
ALBEDO = 0.30             # ما يقتطعه العريُ من المطر (Charney)
ASH_DECAY = 0.51          # ما يبقى من الرماد بعد سنة
ASH_GAIN = 0.055          # عتامةُ الوحدة من قدر الثوران
ASH_CHILL = 0.9           # أثرُ العتامة في الرطوبة
ERUPT_RATE = 1.0 / 45.0   # معدّل الثوران الكبير
ERUPT_TAIL = 1.9          # أُسّ ذيل باريتو للقدر
DUST_BASE = 0.26
DUST_DRY = 0.30           # ما يثيره الجفاف من غبار
DUST_BARE = 0.55          # وما تثيره الأرض العارية
DUST_ASH = 0.25
DUST_LAG = 0.45           # بطءُ استجابة الهواء
# وللهواء ريحُه. ومقدارُه ليس مختارًا ليخرج رقمٌ بعينه: انبعاث الغبار
# يتوقّف على بلل السطح **وعلى عتبة سرعة الريح**، والريح تتقلّب من سنةٍ
# إلى سنة بقدر ما يتقلّب البلل. فسويتُ نصيبَ الاثنين، وأخذتُ الارتباط
# الناتج كما جاء ولم أضبطه ليجيء على قدرٍ أريده.
DUST_NOISE = 0.08
NORM_LAG = 0.025          # زحفُ «المعتاد» في ذهن الناظر
STAR_DAYS = 17.0          # ما يقابل وحدةَ صفاءٍ من أيّام التقويم
STAR_GATE = 0.35          # كم يومًا يُسمّى بعده الطلوعُ مبكّرًا
YIELD_GAIN = 0.46         # ما تعنيه الرطوبة للغلّة
YIELD_ASH = 0.75

#: كل عددٍ ضبطتُه بيدي في هذا الملفّ، ليُحصى في البيان.
TUNED = {k: v for k, v in list(globals().items())
         if k.isupper() and k not in ("PRECESSION", "OBLIQUITY", "ECCENTRIC")}


class Climate:
    """
    حالةُ الجوّ. كلّ ما فيها يتقدّم خطوةً واحدة في السنة بحسابٍ يسير —
    فلا يُثقل الرنّ، وهذا شرط.
    """

    __slots__ = ("T", "h", "hist", "ash", "dust", "norm", "vnorm", "bare",
                 "value", "eruptions", "phase0", "on")

    def __init__(self, cfg, rng):
        self.T = 0.15                 # شذوذ الرطوبة (قوّة الموسم)
        self.h = 0.0                  # ما اختزنه المحيط من حرارة
        self.hist = [0.0] * LAG         # تأخير الشحن — منه يأتي التذبذب
        self.ash = 0.0                # عتامة الرماد البركاني
        self.dust = 0.28              # غبار الهواء
        self.norm = 0.28              # ما اعتاده الناظر من صفاء
        self.bare = 0.0               # ما عُرّي من الأرض
        self.value = 1.0              # المناخ كما يستعمله بقية النظام
        self.vnorm = 1.0              # وما اعتاده الناس من غلّة
        self.eruptions = []           # (سنة، قدر) — للمراقب وحده
        # طورُ الترنّح عند بدء العالم. هذا **شرطٌ ابتدائي مفروض**:
        # اخترتُ لهم زمنًا يبدأ فيه الرطبُ في الانحسار، فيأتي الجدب
        # بعد قرون. ولم أختر الجدب نفسه — اخترتُ موضعهم من الفلك.
        self.phase0 = getattr(cfg, "orbit_phase", 1.15)
        self.on = (bool(getattr(cfg, "sky_orbit", True)),
                   bool(getattr(cfg, "sky_ocean", True)),
                   bool(getattr(cfg, "sky_volcano", True)),
                   bool(getattr(cfg, "sky_albedo", True)))

    # ------------------------------------------------------------ الفلك
    def insolation(self, year):
        """
        فضلُ ما يصل صيفَ المدار من شمس، منسوبًا إلى وسطه ومقيسًا بوحدته.
        ترنّحٌ يضربه شذوذُ المدار، وميلٌ أبطأ منه.
        """
        prec = math.sin(2.0 * math.pi * year / PRECESSION + self.phase0)
        obl = 0.36 * math.cos(2.0 * math.pi * year / OBLIQUITY + 0.6)
        return (prec + obl) / 1.36        # في [−1, 1]

    # ------------------------------------------------------------ البركان
    def _volcano(self, year, rng):
        """
        الرماد ينحلّ أُسّيًّا (عمر النصف نحو سنة)، ويُضاف إليه ما ثار.
        معدّل الثوران الكبير نحو مرّة في خمسٍ وأربعين سنة، وقدرُه من
        ذيلٍ ثقيل: الصغار كثيرة والكبار نادرة وهي التي تُحدث المجاعة.
        """
        self.ash *= ASH_DECAY
        if rng.random() < ERUPT_RATE:
            mag = (1.0 - rng.random()) ** (-1.0 / ERUPT_TAIL) - 1.0  # باريتو
            mag = min(6.0, mag)
            self.ash += ASH_GAIN * mag
            self.eruptions.append((year, round(mag, 2)))
            return mag
        return 0.0

    # ------------------------------------------------------------ الخطوة
    def step(self, year, rng, bare):
        """
        يتقدّم سنةً. `bare` نصيبُ الأرض المعرّاة برعيهم وحرثهم [0,1].
        """
        orbit, ocean, volcano, albedo_on = self.on
        self.bare = bare
        F = self.insolation(year) if orbit else 0.0

        # ردّ فعل الغطاء النباتي: عريٌ ← بياضٌ ← مطرٌ أقلّ (Charney 1975)
        albedo = ALBEDO * bare if albedo_on else 0.0

        # مرجّح الشحن والتفريغ. الرطوبة تستجيب لما اختُزن **قبل ستّ
        # سنين** لا لما اختُزن الآن، والتأخير هو ما يمنع الاستقرار.
        # والتخميد تكعيبيّ فيحدّ السعة بنفسه بلا سقفٍ أضعه أنا.
        #
        # والمرجّح مخمَّدٌ يستثيره التشويش، لا دائمُ الحركة بذاته: وهذا
        # هو حالُ ما يُرصد في المحيط. فالنوبة الرطبة تطول أو تقصر ولا
        # تتكرّر على ميقات، ولا يمكن لأحدٍ أن يتنبّأ بها كما يتنبّأ
        # بالنجم — ومن ادّعى ذلك منهم فقد كذب أو خُدع.
        hd = self.hist[0] if ocean else 0.0
        dT = (K_HEAT * hd - K_DRAG * self.T - K_CUBE * self.T ** 3
              + K_SUN_T * F - albedo - ASH_CHILL * self.ash)
        dh = -K_PULL * self.T - K_LEAK * self.h + K_SUN_H * F
        self.T = max(-2.2, min(2.2, self.T + dT + rng.gauss(0.0, K_NOISE_T)))
        self.h = max(-3.0, min(3.0, self.h + dh + rng.gauss(0.0, K_NOISE_H)))
        self.hist.pop(0)
        self.hist.append(self.h)

        if volcano:
            self._volcano(year, rng)
        else:
            self.ash = 0.0

        # الغبار: يثيره الجفاف والأرض العارية، ويغسله المطر
        # وللغبار سببٌ من نفسه لا من المطر وحده: ريحٌ تهبّ أو تسكن،
        # وعواصفُ تثور في مواضعَ بعيدة. وبغير هذا يصير النجمُ مِيزانًا
        # تامًّا للمطر، فيُكشف الرابط في عشر سنين ولا يبقى فيه شكّ —
        # والعلاماتُ في الدنيا ليست هكذا، وإنما تصدق أكثر ممّا تكذب.
        target = (DUST_BASE - DUST_DRY * self.T + DUST_BARE * bare
                  + DUST_ASH * self.ash + rng.gauss(0.0, DUST_NOISE))
        self.dust += DUST_LAG * (max(0.04, min(1.2, target)) - self.dust)
        # وما اعتاده الناظر يزحف ببطء خلف ما يرى — فالمعتاد ذاكرةٌ لا ثابت
        self.norm += NORM_LAG * (self.dust - self.norm)

        # المناخ كما تراه المحاصيل
        self.value = max(0.35, 1.0 + YIELD_GAIN * self.T - YIELD_ASH * self.ash)
        self.vnorm += NORM_LAG * (self.value - self.vnorm)
        return self.value

    # ------------------------------------------------------------ النجم
    def star_lead(self):
        """
        كم يتقدّم طلوعُ النجم **عمّا اعتاده الناظر**، بالأيّام.

        ولا معنى لـ«مبكّر» بغير معتاد يُقاس إليه؛ والمعتاد نفسه يزحف
        إذا عرَّوا أرضهم فكثُر غبارهم. فالعلامة تبقى صادقة وإن تبدّل
        العالم من تحتها — لأن الناظر يقيس إلى زمانه لا إلى زماني.
        """
        return (self.norm - self.dust) * STAR_DAYS

    def star_early(self):
        return self.star_lead() > STAR_GATE

    def bountiful(self):
        """
        عامٌ خصب — **بالقياس إلى ما اعتادوه**، لا إلى رقمٍ مطلق عندي.

        وكان الخصب يُقاس إلى الواحد الصحيح، فوقعت أربعةُ أخماس السنين
        فوقه في الحقبة الرطبة: أي أن كل عامٍ تقريبًا «خصب»، فلا تبقى
        للكلمة دلالة ولا يبقى للعلامة ما تدلّ عليه. ومن عاش في زمانٍ
        رخيّ لا يسمّي كلَّ عامٍ خيرًا — يسمّي ما زاد على معتاده.

        وهو نفس المبدأ الذي قام عليه «مبكّر» في طلوع النجم: كلاهما
        شذوذٌ عن معتادٍ يزحف، لا عتبةٌ ثابتة كتبتُها.
        """
        return self.value > self.vnorm

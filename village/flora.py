def outcome(plant, dose, prep, mal, body):
    """
    ما تفعله جرعةٌ من نبتةٍ بجسدٍ به علّة. **حقيقةُ العالم، لا رأيُ أحد.**

    يعيد (ما يُنقص من العلّة، ما يُضاف من الأذى).

      النفع = قوّةٌ × مطابقةٌ للآليّة × مقدارٌ يشبع
      الضرّ = سُمٌّ × مقدارٌ **مربّع** — ولذلك يقتل الإفراط ولا ينذر

    ولأن الضرّ يتربّع والنفع يشبع، فلكل نبتةٍ نافعةٍ مقدارٌ أمثل، وما
    بعده ينقلب. ومن لم يعرف المقدار قتل بالدواء.
    """
    y = PREP_YIELD.get(prep, 1.0)
    d = max(0.0, dose) * y

    # **المطابقة اتّجاهٌ لا مقدار.**
    #
    # كانت تُحسب ضربًا داخليًّا محضًا، فكانت النبتة التي تُضادّ كلَّ شيءٍ
    # قليلًا تسبق التي تُضادّ شيئًا واحدًا كثيرًا — فخرجت نبتةٌ واحدة
    # («فُناثة») أفضلَ دواءٍ **لكل الأدواء**. وذلك يهدم المسألة من أصلها:
    # من وجدها مرّةً استغنى عن الطبّ كلّه.
    #
    # فصارت المطابقة جيبَ الزاوية بين متّجهين: لا تُكافأ السَّعة، يُكافأ
    # **الانطباق**. فلكل داءٍ دواؤه، ولا دواءَ لكل داء.
    dot = nrm = 0.0
    for m in range(NM):
        cm = plant.counter[m]
        dot += cm * mal.mech[m]
        nrm += cm * cm
    match = dot / (nrm ** 0.5 + 0.08) if nrm > 0.0 else 0.0
    heal = plant.potency * match * (d / (0.55 + d)) * 2.2
    heal *= (1.0 - getattr(mal, "stubborn", 0.0))
    harm = plant.toxic * PREP_DETOX.get(prep, 1.0) * d * d * 0.55
    # والجسد الواهن يحتمل من السُّمّ أقلّ
    harm *= (1.35 - 0.45 * body)
    return heal, harm


def best_dose(plant, mal):
    """المقدار الأمثل — **للمراقب وحده**، ولا يُستدعى من مسار قرارٍ أبدًا."""
    lo, hi, best, bv = 0.05, 3.0, 0.05, -9.9
    for k in range(40):
        d = lo + (hi - lo) * k / 39.0
        h, x = outcome(plant, d, "نيء", mal, 0.7)
        if h - x > bv:
            best, bv = d, h - x
    return best, bv



"""
النبات — آلافُه، فيه ما يشفي وفيه ما يقتل، وفيه ما يفعل الاثنين.

## القاعدة التي يقوم عليها كلُّ شيء هنا

> «كلُّ شيءٍ سُمّ، ولا شيء بلا سُمّ؛ المقدارُ وحده يفصل بين السُّمّ
> والدواء.» — Paracelsus, 1538

فالنبتة الواحدة تنفع بقليلها وتقتل بكثيرها، ولا يوجد في هذا العالم
«عشبةُ شفاء» ولا «عشبةُ موت» على الإطلاق: يوجد **مقدار**. ومن وجد
نبتةً نفعت مريضًا فأعطى مثلَيها للذي بعده قتله، ثم ظنّ أن النبتة
خدعته — والذي خدعه المقدار.

## ما تحمله النبتة

لكل نبتةٍ متّجهٌ خفيّ: كم تُضادّ كلَّ آليّةٍ من آليّات الأدواء الثماني
(عفن، حُمّى، سُمّ، نقص، احتقان، نزف، تشنّج، هزال). ونفعُها في داءٍ
بعينه = مطابقةُ متّجهها لآليّة ذلك الداء. **ولذلك ينفع الدواءُ الواحد
أدواءً تبدو مختلفة، ولا ينفع داءً يشبهها في أعراضه** — وهذا هو أصعب
ما في الطبّ، وهو الذي يجعل التجربة تكذب على صاحبها.

## ما لا يعرفونه أبدًا

لا يقرأ الكائن `counter` ولا `toxic` ولا `potency`. يرى شيئًا واحدًا:
أعطيتُ فلانًا هذه النبتة وهو على هذه الحال، فصار إلى كذا. ثم يتذكّر —
وذاكرتُه تخونه، وقد يُشفى المريض بغير دواء فيُنسب الشفاء إلى النبتة،
وقد يموت وهو على الدواء النافع فتُتّهم النبتة الصالحة.

**ولا نصحّح لهم ولا نلمّح.**
"""

import random

from .malady import NM

#: كم نبتةً في هذا العالم.
N_PLANTS = 3200

#: الأجزاء المستعملة — تختلف قوّتها وسمّيتها في النبتة الواحدة
PARTS = ("ورق", "جذر", "بذر", "لِحاء", "زهر", "ثمر", "صمغ")

#: طرق الإعداد. وهي تغيّر ما يخرج من النبتة — والغلي يُذهب بعض السُّمّ.
PREPS = ("نيء", "مغليّ", "منقوع", "مسحوق", "مضمَّد", "محروق")
PREP_YIELD = {"نيء": 1.00, "مغليّ": 0.85, "منقوع": 0.75,
              "مسحوق": 0.95, "مضمَّد": 0.60, "محروق": 0.55}
#: والغلي يهدم من السُّمّ أكثر ممّا يهدم من الدواء — ومن عرف هذا سبق قومه
PREP_DETOX = {"نيء": 1.00, "مغليّ": 0.55, "منقوع": 0.70,
              "مسحوق": 1.00, "مضمَّد": 0.80, "محروق": 0.45}

_A = ("عُ", "شَ", "بَ", "قُ", "زَ", "نِ", "حَ", "سُ", "مِ", "طَ", "ثُ", "خِ",
      "دَ", "رُ", "لِ", "غَ", "فُ", "كِ", "وَ", "يُ")
_B = ("رام", "شان", "لود", "مير", "ناث", "قيل", "دام", "سور", "تين", "بال",
      "ران", "خيم", "زول", "عاد", "هير", "فام", "جون", "طاس", "ميل", "كار")
_C = ("", "", "", "ة", "ان", "ي", "ون")


def _coin(rng):
    return rng.choice(_A) + rng.choice(_B) + rng.choice(_C)


class Plant:
    """
    نبتة. كلُّ ما فيها عدا الاسم والموضع **سرٌّ لا يُقرأ من داخل عقل
    أحدٍ منهم**.
    """

    __slots__ = ("id", "name", "counter", "toxic", "potency", "biomes",
                 "part", "rarity", "tried", "known_by")

    def __init__(self, i, name, counter, toxic, potency, biomes, part, rarity):
        self.id = i
        self.name = name
        self.counter = counter     # سرّ: ما تُضادّه من الآليّات
        self.toxic = toxic         # سرّ: ما تُهلك به
        self.potency = potency     # سرّ: قوّتها
        self.biomes = biomes       # ظاهر: أين تنبت
        self.part = part
        self.rarity = rarity
        self.tried = 0             # للمراقب: كم مرّةً جُرّبت
        self.known_by = 0

    def window(self):
        """
        سَعةُ النافذة العلاجية للمراقب: كم يفصل بين المقدار النافع
        والمقدار القاتل. الضيّقةُ منها هي التي تقتل من يجرّبها.
        """
        return self.potency / (0.02 + self.toxic)


def build(seed=20260910, n=N_PLANTS):
    """
    تُبنى مرّةً واحدة وهي ثابتةٌ بين الرنّات — نباتُ هذا العالم واحد،
    والذي يختلف بين رنٍّ ورنّ هو ما عرفوه منه.
    """
    rng = random.Random(seed ^ 0x5EED)
    out = []
    for i in range(n):
        # أكثرُ النبات لا يفعل شيئًا يُذكر — وهذا هو الواقع، ولولاه
        # لكان كلُّ من مدّ يده إلى عشبةٍ طبيبًا.
        r = rng.random()
        if r < 0.62:                       # خاملٌ أو يكاد
            k = rng.randrange(NM)
            counter = [0.0] * NM
            counter[k] = 0.05 + 0.25 * rng.random()
            potency = 0.05 + 0.20 * rng.random()
            toxic = 0.01 + 0.09 * rng.random()
        elif r < 0.82:                     # نافعٌ رفيق
            counter = [0.0] * NM
            for _ in range(rng.randint(1, 2)):
                counter[rng.randrange(NM)] += 0.45 + 0.45 * rng.random()
            potency = 0.35 + 0.35 * rng.random()
            toxic = 0.02 + 0.13 * rng.random()
        elif r < 0.93:                     # قويٌّ خطر — نافذته ضيّقة
            counter = [0.0] * NM
            for _ in range(rng.randint(1, 3)):
                counter[rng.randrange(NM)] += 0.60 + 0.60 * rng.random()
            potency = 0.70 + 0.60 * rng.random()
            toxic = 0.35 + 0.55 * rng.random()
        else:                              # سُمٌّ محض
            counter = [0.0] * NM
            if rng.random() < 0.35:
                counter[rng.randrange(NM)] = 0.10 * rng.random()
            potency = 0.02 + 0.08 * rng.random()
            toxic = 0.80 + 1.20 * rng.random()

        nb = rng.randint(1, 2)
        biomes = tuple(sorted(rng.sample(range(6), nb)))
        out.append(Plant(i, _coin(rng), counter, toxic, potency, biomes,
                         rng.choice(PARTS), 0.15 + 0.85 * rng.random()))
    return out


def by_biome(plants):
    """فهرسٌ للموضع — فلا يُبحث في ثلاثة آلافٍ في كل مرّة."""
    idx = [[] for _ in range(6)]
    for p in plants:
        for b in p.biomes:
            idx[b].append(p)
    return idx



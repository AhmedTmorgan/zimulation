"""
Concept formation, verified on experiences generated by the real physics.

Things are made from the world's materials, perceived by handling through
the real perception module, and paired with outcomes the body would
register. The learner is never told what anything is. The test, playing
observer, knows which material each experience came from and uses that
only to score how well the learner's own categories line up with it.

    python -m tests.v2.test_concepts
"""

